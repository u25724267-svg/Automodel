"""Run pinned author benchmark tasks through EleutherAI LM Evaluation Harness."""

from __future__ import annotations

import argparse
import importlib.util
import json
import logging
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

logger = logging.getLogger(__name__)

LM_EVAL_COMMIT = "f4d4b3de3ee6741a7151a9fe74945ee515262f4c"
IROKOBENCH_COMMIT = "1f8be590da6699aee3dc23de6f63e801e2352eff"
BELEBELE_COMMIT = "918890beb2290a8d3ef2d7a90369925959e1bacf"
LANGUAGES = ("eng", "hau", "ibo", "kin", "swa", "xho", "yor", "zul")
PROMPT_IDS = (1, 2, 3, 4, 5)


@dataclass(frozen=True)
class BenchmarkRun:
    """Declarative settings for one upstream benchmark invocation."""

    suite: Literal["irokobench", "belebele", "all"]
    base_model: str
    output_dir: Path
    checkpoint_path: Path | None = None
    languages: tuple[str, ...] = LANGUAGES
    prompt_ids: tuple[int, ...] = PROMPT_IDS
    device: str = "cuda:0"
    batch_size: int = 1
    limit: int | None = None


def task_names(run: BenchmarkRun) -> list[str]:
    """Return exact task names generated by the pinned upstream harness."""
    tasks = []
    for prompt_id in run.prompt_ids:
        for language in run.languages:
            if run.suite in ("irokobench", "all"):
                tasks.extend(
                    [
                        f"afrimmlu_direct_{language}_prompt_{prompt_id}",
                        f"afrixnli_{language}_prompt_{prompt_id}",
                        f"afrimgsm_cot_{language}_prompt_{prompt_id}",
                    ]
                )
            if run.suite in ("belebele", "all"):
                tasks.append(f"belebele_{language}_prompt_{prompt_id}")
    return tasks


def model_arguments(run: BenchmarkRun) -> str:
    """Return model arguments for upstream Gemma 4 VLM and PEFT loading."""
    arguments = [
        f"pretrained={run.base_model}",
        "dtype=bfloat16",
        "attn_implementation=sdpa",
    ]
    if run.checkpoint_path is not None:
        adapter_dir = run.checkpoint_path / "model"
        required = (adapter_dir / "adapter_config.json", adapter_dir / "adapter_model.safetensors")
        missing = [str(path) for path in required if not path.is_file()]
        if missing:
            raise FileNotFoundError(f"Checkpoint is missing standard PEFT files: {missing}")
        arguments.append(f"peft={adapter_dir}")
    return ",".join(arguments)


def build_command(run: BenchmarkRun, *, command_prefix: tuple[str, ...] = ("lm-eval",)) -> list[str]:
    """Build the author-aligned LM Evaluation Harness command."""
    command = [
        *command_prefix,
        "run",
        "--model",
        "hf-multimodal",
        "--model_args",
        model_arguments(run),
        "--tasks",
        ",".join(task_names(run)),
        "--device",
        run.device,
        "--batch_size",
        str(run.batch_size),
        "--num_fewshot",
        "0",
        "--apply_chat_template",
        "--log_samples",
        "--show_config",
        "--output_path",
        str(run.output_dir),
    ]
    if run.limit is not None:
        command.extend(("--limit", str(run.limit)))
    return command


def run_benchmarks(run: BenchmarkRun, *, dry_run: bool = False) -> dict[str, object]:
    """Record provenance and execute the pinned upstream benchmark tasks."""
    if importlib.util.find_spec("lm_eval") is None and not dry_run:
        raise FileNotFoundError("lm-eval is not installed; run `uv sync --extra benchmark`")
    compatibility_bootstrap = Path(__file__).with_name("lm_eval_compat.py")
    command = build_command(run, command_prefix=(sys.executable, str(compatibility_bootstrap)))
    run.output_dir.mkdir(parents=True, exist_ok=True)
    provenance = {
        "suite": run.suite,
        "base_model": run.base_model,
        "checkpoint_path": str(run.checkpoint_path) if run.checkpoint_path is not None else None,
        "languages": list(run.languages),
        "prompt_ids": list(run.prompt_ids),
        "task_count": len(task_names(run)),
        "command": command,
        "upstream_revisions": {
            "lm_evaluation_harness": LM_EVAL_COMMIT,
            "masakhane_nlu": IROKOBENCH_COMMIT,
            "belebele": BELEBELE_COMMIT,
        },
        "author_alignment": {
            "multiple_choice": "upstream loglikelihood tasks and accuracy aggregation",
            "afrimgsm": "upstream generate_until, CoT prompts, filters, and exact-match aggregation",
            "prompt_policy": "all five author prompt variants, reported separately",
            "compatibility_patch": (
                "Expose lm_eval.utils.weighted_f1_score to pinned AfriMMLU/AfriXNLI prompt modules; "
                "no task templates, requests, filters, predictions, or aggregators are replaced"
            ),
        },
    }
    (run.output_dir / "run_provenance.json").write_text(
        json.dumps(provenance, indent=2) + "\n",
        encoding="utf-8",
    )
    if not dry_run:
        subprocess.run(command, check=True)
    return provenance


def _csv_strings(value: str) -> tuple[str, ...]:
    return tuple(item.strip() for item in value.split(",") if item.strip())


def _csv_ints(value: str) -> tuple[int, ...]:
    return tuple(int(item) for item in _csv_strings(value))


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite", choices=("irokobench", "belebele", "all"), default="all")
    parser.add_argument("--base-model", default="google/gemma-4-E2B-it")
    parser.add_argument("--checkpoint-path", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--languages", type=_csv_strings, default=LANGUAGES)
    parser.add_argument("--prompt-ids", type=_csv_ints, default=PROMPT_IDS)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--dry-run", action="store_true")
    return parser


def main() -> int:
    """Run the configured author benchmark suite."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)s | %(message)s")
    args = _build_parser().parse_args()
    unknown_languages = set(args.languages) - set(LANGUAGES)
    if unknown_languages:
        raise ValueError(f"Unsupported language configurations: {sorted(unknown_languages)}")
    unknown_prompts = set(args.prompt_ids) - set(PROMPT_IDS)
    if unknown_prompts:
        raise ValueError(f"Unsupported author prompt IDs: {sorted(unknown_prompts)}")
    run = BenchmarkRun(
        suite=args.suite,
        base_model=args.base_model,
        checkpoint_path=args.checkpoint_path.resolve() if args.checkpoint_path is not None else None,
        output_dir=args.output_dir.resolve(),
        languages=args.languages,
        prompt_ids=args.prompt_ids,
        device=args.device,
        batch_size=args.batch_size,
        limit=args.limit,
    )
    provenance = run_benchmarks(run, dry_run=args.dry_run)
    logger.info("Configured %d pinned upstream tasks", provenance["task_count"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
